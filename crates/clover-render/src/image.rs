//! Image decoding and storage.
//!
//! Decoded images are converted to premultiplied BGRA once, at load time, so the
//! tile renderer only ever blits.

use std::collections::HashMap;
use std::path::Path;
use std::sync::Arc;

use clover_core::Size;
use clover_ui::ImageHandle;

use crate::canvas::ImagePixels;

/// Decodes a PNG file from disk.
pub fn decode_png_file(path: impl AsRef<Path>) -> Result<ImagePixels, String> {
    let bytes = std::fs::read(path.as_ref()).map_err(|e| format!("read failed: {e}"))?;
    decode_png_bytes(&bytes)
}

/// Decodes PNG bytes into premultiplied pixels.
pub fn decode_png_bytes(bytes: &[u8]) -> Result<ImagePixels, String> {
    let decoder = png::Decoder::new(std::io::Cursor::new(bytes));
    let mut reader = decoder.read_info().map_err(|e| format!("png header: {e}"))?;
    let mut buffer = vec![0; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buffer).map_err(|e| format!("png data: {e}"))?;
    buffer.truncate(info.buffer_size());

    let (width, height) = (info.width, info.height);
    let rgba = match info.color_type {
        png::ColorType::Rgba => buffer,
        png::ColorType::Rgb => {
            let mut out = Vec::with_capacity(buffer.len() / 3 * 4);
            for chunk in buffer.chunks_exact(3) {
                out.extend_from_slice(&[chunk[0], chunk[1], chunk[2], 255]);
            }
            out
        }
        png::ColorType::GrayscaleAlpha => {
            let mut out = Vec::with_capacity(buffer.len() * 2);
            for chunk in buffer.chunks_exact(2) {
                out.extend_from_slice(&[chunk[0], chunk[0], chunk[0], chunk[1]]);
            }
            out
        }
        png::ColorType::Grayscale => {
            let mut out = Vec::with_capacity(buffer.len() * 4);
            for value in buffer {
                out.extend_from_slice(&[value, value, value, 255]);
            }
            out
        }
        png::ColorType::Indexed => return Err("indexed PNG is not supported".into()),
    };

    Ok(ImagePixels::from_rgba8(width, height, &rgba))
}

/// Registry of images addressable from the UI tree.
#[derive(Default)]
pub struct ImageStore {
    images: HashMap<ImageHandle, Arc<ImagePixels>>,
    next: u64,
}

impl ImageStore {
    pub fn new() -> Self {
        Self { images: HashMap::new(), next: 1 }
    }

    /// Registers decoded pixels and returns a handle.
    pub fn insert(&mut self, pixels: ImagePixels) -> ImageHandle {
        let handle = ImageHandle(self.next);
        self.next += 1;
        self.images.insert(handle, Arc::new(pixels));
        handle
    }

    /// Loads a PNG from disk and registers it.
    pub fn load_png(&mut self, path: impl AsRef<Path>) -> Result<ImageHandle, String> {
        let pixels = decode_png_file(path)?;
        Ok(self.insert(pixels))
    }

    pub fn get(&self, handle: ImageHandle) -> Option<&Arc<ImagePixels>> {
        self.images.get(&handle)
    }

    pub fn measure(&self, handle: ImageHandle) -> Size {
        self.images
            .get(&handle)
            .map(|img| Size::new(img.width as f32, img.height as f32))
            .unwrap_or(Size::ZERO)
    }

    pub fn len(&self) -> usize {
        self.images.len()
    }

    pub fn is_empty(&self) -> bool {
        self.images.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A 2x2 PNG generated by clover-render's own encoder path in tests.
    fn tiny_png() -> Vec<u8> {
        let mut bytes = Vec::new();
        {
            let mut encoder = png::Encoder::new(&mut bytes, 2, 2);
            encoder.set_color(png::ColorType::Rgba);
            encoder.set_depth(png::BitDepth::Eight);
            let mut writer = encoder.write_header().unwrap();
            let data: [u8; 16] = [
                255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 128,
            ];
            writer.write_image_data(&data).unwrap();
        }
        bytes
    }

    #[test]
    fn decodes_rgba_png() {
        let image = decode_png_bytes(&tiny_png()).unwrap();
        assert_eq!(image.width, 2);
        assert_eq!(image.height, 2);
        assert_eq!(image.pixels.len(), 4);
    }

    #[test]
    fn premultiplies_at_load() {
        let image = decode_png_bytes(&tiny_png()).unwrap();
        // Bottom-right pixel is white at 50% alpha.
        assert_eq!(image.pixels[3] >> 24, 128, "alpha preserved");
        assert!((image.pixels[3] & 0xFF) < 200, "colour premultiplied");
    }

    #[test]
    fn store_tracks_handles() {
        let mut store = ImageStore::new();
        let image = decode_png_bytes(&tiny_png()).unwrap();
        let handle = store.insert(image);
        assert_eq!(store.len(), 1);
        assert_eq!(store.measure(handle), Size::new(2.0, 2.0));
        assert!(store.get(handle).is_some());
    }

    #[test]
    fn rejects_garbage() {
        assert!(decode_png_bytes(b"not a png").is_err());
    }
}
